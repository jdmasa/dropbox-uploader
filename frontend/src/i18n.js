const DICTS = { ca, es, en };
let lang = 'ca';

export function setLang(code) {
  lang = DICTS[code] ? code : 'ca';
  document.documentElement.lang = lang;
}

export function getLang() { return lang; }

// t('key', {name: 'x'}) -> translated string with {placeholders} filled in.
export function t(key, params = {}) {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

// Plural-aware: uses key_one when n === 1, key_other otherwise.
export function tn(key, n, params = {}) {
  return t(`${key}_${n === 1 ? 'one' : 'other'}`, { n, ...params });
}

// Errors from the Go side are sent as "err.code" or "err.code|detail".
export function tErr(message) {
  const m = /^(err\.[A-Za-z]+)(?:\|([\s\S]*))?$/.exec(String(message ?? '').trim());
  if (!m) return String(message || t('err.generic'));
  return t(m[1], { 0: m[2] ?? '' });
}

// Fill elements marked with data-i18n (text), data-i18n-html, data-i18n-title, data-i18n-placeholder.
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
